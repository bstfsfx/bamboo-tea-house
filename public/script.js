// https://www.xe.com/currencyconverter/convert/?Amount=1&From=TWD&To=USD
// https://www.xe.com/currencyconverter/convert/?Amount=1&From=TWD&To=CNY
// https://www.xe.com/currencyconverter/convert/?Amount=1&From=TWD&To=JPY
// https://www.xe.com/currencyconverter/convert/?Amount=1&From=TWD&To=EUR
const menuPriceRates = {
  ja: { rate: 4.828611, rounding: 10, prefix: '¥', precision: 0, numberLocale: 'ja-JP' },
  'zh-Hant': { rate: 1, rounding: 1, prefix: 'NTD ', precision: 0, numberLocale: 'zh-TW' },
  'zh-Hans': { rate: 0.204785, rounding: 1, prefix: 'RMB ', precision: 0, numberLocale: 'zh-CN' },
  en: { rate: 0.0306800, rounding: 0.01, prefix: 'USD ', precision: 2, numberLocale: 'en-US' },
  fr: { rate: 0.0272893, rounding: 0.01, precision: 2, numberLocale: 'fr-FR', currency: 'EUR' },
  es: { rate: 0.0272893, rounding: 0.01, precision: 2, numberLocale: 'es-ES', currency: 'EUR' }
};

function formatMenuPrice(priceNtd, locale) {
  const currency = menuPriceRates[locale];
  const converted = priceNtd * currency.rate;
  const amount = Math.round(converted / currency.rounding) * currency.rounding;
  const formatted = new Intl.NumberFormat(currency.numberLocale, {
    ...(currency.currency ? { style: 'currency', currency: currency.currency } : {}),
    minimumFractionDigits: currency.precision,
    maximumFractionDigits: currency.precision
  }).format(amount);
  return currency.prefix ? `${currency.prefix}${formatted}` : formatted;
}

const menuToggle = document.querySelector('.menu-toggle');
const primaryNav = document.querySelector('.primary-nav');
const searchToggle = document.querySelector('.search-toggle');
const searchPanel = document.querySelector('.search-panel');
const searchInput = document.querySelector('#search-input');
const searchClose = document.querySelector('.search-close');
const searchStatus = document.querySelector('#search-status');
const languageSelect = document.querySelector('#language-select');
const searchableItems = [...document.querySelectorAll('.searchable')];

function browserLocale() {
  const tag = (navigator.language || '').toLowerCase();
  if (tag.startsWith('ja')) return 'ja';
  if (tag.startsWith('en')) return 'en';
  if (tag.startsWith('fr')) return 'fr';
  if (tag.startsWith('es')) return 'es';
  if (tag.startsWith('zh')) return /(hans|cn|sg)/i.test(tag) ? 'zh-Hans' : 'zh-Hant';
  return defaultLocale;
}

function applyLocale(locale, remember = false) {
  activeLocale = supportedLocales.includes(locale) ? locale : defaultLocale;
  const t = messages[activeLocale];
  document.documentElement.lang = activeLocale;

  document.querySelectorAll('[data-i18n]').forEach((node) => {
    const value = t[node.dataset.i18n];
    if (value !== undefined) node.textContent = value;
  });
  document.querySelectorAll('[data-price-ntd]').forEach((node) => {
    node.textContent = formatMenuPrice(Number(node.dataset.priceNtd), activeLocale);
  });
  document.querySelectorAll('[data-i18n-alt]').forEach((node) => {
    const value = t[node.dataset.i18nAlt];
    if (value !== undefined) node.setAttribute('alt', value);
  });
  document.querySelectorAll('[data-i18n-aria-label]').forEach((node) => {
    const value = t[node.dataset.i18nAriaLabel];
    if (value !== undefined) node.setAttribute('aria-label', value);
  });
  document.querySelectorAll('[data-i18n-content]').forEach((node) => {
    const value = t[node.dataset.i18nContent];
    if (value !== undefined) node.setAttribute('content', value);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((node) => {
    const value = t[node.dataset.i18nPlaceholder];
    if (value !== undefined) node.setAttribute('placeholder', value);
  });

  document.title = t.metaTitle;
  if (languageSelect) languageSelect.value = activeLocale;
  if (menuToggle) {
    const isOpen = menuToggle.getAttribute('aria-expanded') === 'true';
    menuToggle.setAttribute('aria-label', isOpen ? t.menuClose : t.menuOpen);
  }
  if (searchStatus && searchInput?.value.trim()) {
    const visible = searchableItems.some((item) => !item.hidden);
    searchStatus.textContent = visible ? '' : t.searchNoResults;
  }
  if (remember) {
    try { localStorage.setItem('bamboo-tea-locale', activeLocale); } catch { /* Storage may be disabled by the browser. */ }
  }
}

function preferredLocale() {
  try {
    const saved = localStorage.getItem('bamboo-tea-locale');
    if (supportedLocales.includes(saved)) return saved;
  } catch { /* Use the browser language when storage is unavailable. */ }
  return browserLocale();
}

menuToggle?.addEventListener('click', () => {
  const isOpen = menuToggle.getAttribute('aria-expanded') === 'true';
  menuToggle.setAttribute('aria-expanded', String(!isOpen));
  menuToggle.setAttribute('aria-label', isOpen ? messages[activeLocale].menuOpen : messages[activeLocale].menuClose);
  primaryNav?.classList.toggle('is-open', !isOpen);
});

primaryNav?.querySelectorAll('a').forEach((link) => {
  link.addEventListener('click', () => {
    primaryNav.classList.remove('is-open');
    menuToggle?.setAttribute('aria-expanded', 'false');
    menuToggle?.setAttribute('aria-label', messages[activeLocale].menuOpen);
  });
});

function setSearchOpen(open) {
  if (!searchPanel || !searchToggle) return;
  searchPanel.hidden = !open;
  searchToggle.setAttribute('aria-expanded', String(open));
  if (open) searchInput?.focus();
}

searchToggle?.addEventListener('click', () => setSearchOpen(searchPanel.hidden));
searchClose?.addEventListener('click', () => {
  setSearchOpen(false);
  if (searchInput) searchInput.value = '';
  searchableItems.forEach((item) => { item.hidden = false; });
  if (searchStatus) searchStatus.textContent = '';
});

searchInput?.addEventListener('input', () => {
  const term = searchInput.value.trim().toLocaleLowerCase();
  let visibleCount = 0;
  searchableItems.forEach((item) => {
    const searchableText = `${item.dataset.search || ''} ${item.textContent || ''}`.toLocaleLowerCase();
    const matches = !term || searchableText.includes(term);
    item.hidden = !matches;
    if (matches) visibleCount += 1;
  });
  if (searchStatus) {
    searchStatus.textContent = term && visibleCount === 0 ? messages[activeLocale].searchNoResults : '';
  }
});

languageSelect?.addEventListener('change', () => {
  applyLocale(languageSelect.value, true);
  searchInput?.dispatchEvent(new Event('input', { bubbles: true }));
});

document.addEventListener('keydown', (event) => {
  if (event.key === 'Escape' && searchPanel && !searchPanel.hidden) {
    setSearchOpen(false);
    searchToggle?.focus();
  }
});

applyLocale(preferredLocale());

const hero = document.querySelector('.hero');
const prefersReducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)');
if (hero && !prefersReducedMotion.matches) {
  let parallaxFrame = 0;
  const updateHeroParallax = () => {
    parallaxFrame = 0;
    const rect = hero.getBoundingClientRect();
    if (rect.bottom <= 0 || rect.top >= window.innerHeight) return;

    const mobile = window.matchMedia('(max-width: 560px)').matches;
    const strength = mobile ? 0.055 : 0.11;
    const limit = mobile ? 18 : 36;
    const offset = Math.max(-limit, Math.min(limit, window.scrollY * strength));
    hero.style.setProperty('--hero-parallax-offset', `${offset.toFixed(1)}px`);
  };
  const requestHeroParallax = () => {
    if (!parallaxFrame) parallaxFrame = window.requestAnimationFrame(updateHeroParallax);
  };

  hero.classList.add('has-parallax');
  window.addEventListener('scroll', requestHeroParallax, { passive: true });
  window.addEventListener('resize', requestHeroParallax, { passive: true });
  requestHeroParallax();
}

if (!prefersReducedMotion.matches && 'IntersectionObserver' in window) {
  const revealTargets = document.querySelectorAll(
    '.featured__intro, .product-card, .story__photo, .story__copy-inner, .story__room, .visit__intro, .experience-card, .location-card'
  );
  ['.product-card', '.experience-card'].forEach((selector) => {
    document.querySelectorAll(selector).forEach((item, index) => {
      item.style.setProperty('--reveal-delay', `${(index % 4) * 40}ms`);
    });
  });

  if (revealTargets.length) {
    revealTargets.forEach((target) => target.classList.add('reveal-item'));
    const revealObserver = new IntersectionObserver((entries, observer) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        entry.target.classList.add('is-visible');
        observer.unobserve(entry.target);
      });
    }, { rootMargin: '0px 0px -6% 0px', threshold: 0.12 });

    revealTargets.forEach((target) => revealObserver.observe(target));
    document.body.classList.add('reveal-enabled');
  }
}
